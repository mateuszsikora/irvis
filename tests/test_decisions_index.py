"""Tests for scripts/decisions-index.py. Plain temporary directories; no git needed."""
from __future__ import annotations

import contextlib
import importlib.util
import io
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

REPO = Path(__file__).resolve().parent.parent


def load():
    spec = importlib.util.spec_from_file_location("decisions_index", REPO / "scripts" / "decisions-index.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod  # dataclasses look their module up here
    spec.loader.exec_module(mod)
    return mod


mod = load()

DECISIONS = """\
---
title: front matter is skipped
---
# Build decisions

## Use make for build targets

Status: decided (#3)

Reasoning.

**Rejected:** a shell script, because make is already installed.

Ship a container image
----------------------

Status: postponed

```md
## Not a heading inside fenced code
```
"""


class SlugTests(unittest.TestCase):
    def test_slugs_match_github(self):
        cases = {
            "Tests use unittest, not pytest": "tests-use-unittest-not-pytest",
            "`SKIP_DOCS_CHECK` is ignored in CI": "skip_docs_check-is-ignored-in-ci",
            "What's new?": "whats-new",
            "A -- B": "a----b",
            "**Bold** and [a link](x.md)": "bold-and-a-link",
            "Zażółć gęślą": "zażółć-gęślą",
            "`<feature>-user.md`": "feature-usermd",
            "Use `<T>` generics": "use-t-generics",
            "The `_private` helper": "the-_private-helper",
            "[`foo`](bar.md)": "foo",
            "[`check-docs.py`](../../scripts/check-docs.py)": "check-docspy",
            "` x ` y": "x-y",
        }
        for text, slug in cases.items():
            self.assertEqual(mod.slugify(text), slug, text)

    def test_duplicate_headings_get_suffixes(self):
        slugs = [h.slug for h in mod.headings("## Same\n\n## Same\n\n## Same\n")]
        self.assertEqual(slugs, ["same", "same-1", "same-2"])

    def test_headings_skip_code_and_front_matter(self):
        found = [(h.level, h.text) for h in mod.headings(DECISIONS)]
        self.assertEqual(found, [(1, "Build decisions"), (2, "Use make for build targets"),
                                 (2, "Ship a container image")])

    def test_html_ids_are_anchors(self):
        self.assertIn("custom", mod.anchors('<a id="custom"></a>\n\n# Title\n'))


class IndexTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        (self.root / "docs/decisions").mkdir(parents=True)
        self.domains = {"build": "Build"}
        self.write("build.md", DECISIONS)

    def write(self, name, text):
        (self.root / "docs/decisions" / name).write_text(text, encoding="utf-8")

    def generate(self):
        text, errors = mod.render(str(self.root), self.domains)
        self.assertEqual(errors, [])
        self.write("README.md", text)
        return text

    def test_render_lists_decisions_with_anchor_and_status(self):
        text = self.generate()
        self.assertTrue(text.startswith("# Decisions index\n\nGenerated by `scripts/decisions-index.py`, do not edit by hand."))
        self.assertIn("| [Use make for build targets](build.md#use-make-for-build-targets) | [build.md](build.md) | decided (#3) |", text)
        self.assertIn("| [Ship a container image](build.md#ship-a-container-image) | [build.md](build.md) | postponed |", text)
        self.assertNotIn("Not a heading", text)

    def test_fresh_index_passes_check(self):
        self.generate()
        self.assertEqual(mod.check(str(self.root), self.domains), [])

    def test_stale_index_fails_check(self):
        self.generate()
        with open(self.root / "docs/decisions/build.md", "a", encoding="utf-8") as f:
            f.write("\n## Another decision\n\nStatus: decided\n")
        self.assertEqual(mod.check(str(self.root), self.domains),
                         ["docs/decisions/README.md is stale: run `make decisions-index`"])

    def test_unlisted_file_fails_check(self):
        self.write("other.md", "# Other\n")
        self.generate()
        self.assertIn("docs/decisions/other.md is not listed in DOMAINS in scripts/decisions-index.py",
                      mod.check(str(self.root), self.domains))

    def test_listed_domain_without_file_fails_check(self):
        self.generate()
        problems = mod.check(str(self.root), {**self.domains, "ci": "CI"})
        self.assertIn("DOMAINS in scripts/decisions-index.py lists 'ci', but docs/decisions/ci.md does not exist",
                      problems)

    def test_missing_status_is_an_error(self):
        self.write("build.md", "# Build\n\n## A decision without status\n\nJust text.\n")
        _, errors = mod.render(str(self.root), self.domains)
        self.assertEqual(len(errors), 1)
        self.assertIn("decision 'A decision without status' needs 'Status:", errors[0])

    def test_main_check_exit_codes(self):
        with mock.patch.dict(mod.DOMAINS, self.domains, clear=True), contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(mod.main([], root=str(self.root)), 0)
            self.assertEqual(mod.main(["--check"], root=str(self.root)), 0)
            self.write("README.md", "edited by hand\n")
            self.assertEqual(mod.main(["--check"], root=str(self.root)), 1)


if __name__ == "__main__":
    unittest.main()
