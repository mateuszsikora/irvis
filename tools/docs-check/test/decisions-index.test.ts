import { appendFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { DECISIONS_DIR, check, main, render } from '../src/decisions-index.ts';
import { anchors, headings, slugify } from '../src/markdown.ts';

const DECISIONS = `---
title: front matter is skipped
---
# Build decisions

## Use npm scripts for build targets

Status: decided (#3)

Reasoning.

**Rejected:** a shell script, because npm is already installed.

Ship a container image
----------------------

Status: postponed

\`\`\`md
## Not a heading inside fenced code
\`\`\`
`;

describe('slugs', () => {
  it('slugs match github', () => {
    const cases: Record<string, string> = {
      'Tests use Vitest, not Jest': 'tests-use-vitest-not-jest',
      '`SKIP_DOCS_CHECK` is ignored in CI': 'skip_docs_check-is-ignored-in-ci',
      "What's new?": 'whats-new',
      'A -- B': 'a----b',
      '**Bold** and [a link](x.md)': 'bold-and-a-link',
      'Zażółć gęślą': 'zażółć-gęślą',
      '`<feature>-user.md`': 'feature-usermd',
      'Use `<T>` generics': 'use-t-generics',
      'The `_private` helper': 'the-_private-helper',
      '[`foo`](bar.md)': 'foo',
      '[`check-docs.ts`](../src/check-docs.ts)': 'check-docsts',
      '` x ` y': 'x-y',
    };
    for (const [text, slug] of Object.entries(cases)) {
      expect(slugify(text), text).toBe(slug);
    }
  });

  it('duplicate headings get suffixes', () => {
    const slugs = headings('## Same\n\n## Same\n\n## Same\n').map((h) => h.slug);
    expect(slugs).toEqual(['same', 'same-1', 'same-2']);
  });

  it('headings skip code and front matter', () => {
    const found = headings(DECISIONS).map((h) => [h.level, h.text]);
    expect(found).toEqual([
      [1, 'Build decisions'],
      [2, 'Use npm scripts for build targets'],
      [2, 'Ship a container image'],
    ]);
  });

  it('html ids are anchors', () => {
    expect(anchors('<a id="custom"></a>\n\n# Title\n')).toContain('custom');
  });
});

describe('decisions index', () => {
  let root: string;
  let domains: Record<string, string>;

  function write(name: string, text: string): void {
    writeFileSync(join(root, DECISIONS_DIR, name), text);
  }

  function generate(): string {
    const [text, errors] = render(root, domains);
    expect(errors).toEqual([]);
    write('README.md', text);
    return text;
  }

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'decisions-index-'));
    mkdirSync(join(root, 'docs/decisions'), { recursive: true });
    domains = { build: 'Build' };
    write('build.md', DECISIONS);
  });
  afterEach(() => rmSync(root, { recursive: true, force: true }));

  it('render lists decisions with anchor and status', () => {
    const text = generate();
    expect(text).toMatch(
      /^# Decisions index\n\nGenerated by `tools\/docs-check\/src\/decisions-index\.ts`, do not edit by hand\./,
    );
    expect(text).toContain(
      '| [Use npm scripts for build targets](build.md#use-npm-scripts-for-build-targets) | [build.md](build.md) | decided (#3) |',
    );
    expect(text).toContain(
      '| [Ship a container image](build.md#ship-a-container-image) | [build.md](build.md) | postponed |',
    );
    expect(text).not.toContain('Not a heading');
  });

  it('fresh index passes check', () => {
    generate();
    expect(check(root, domains)).toEqual([]);
  });

  it('stale index fails check', () => {
    generate();
    appendFileSync(
      join(root, 'docs/decisions/build.md'),
      '\n## Another decision\n\nStatus: decided\n',
    );
    expect(check(root, domains)).toEqual([
      'docs/decisions/README.md is stale: run `npm run decisions-index`',
    ]);
  });

  it('unlisted file fails check', () => {
    write('other.md', '# Other\n');
    generate();
    expect(check(root, domains)).toContain(
      'docs/decisions/other.md is not listed in DOMAINS in tools/docs-check/src/decisions-index.ts',
    );
  });

  it('listed domain without file fails check', () => {
    generate();
    expect(check(root, { ...domains, ci: 'CI' })).toContain(
      "DOMAINS in tools/docs-check/src/decisions-index.ts lists 'ci', but docs/decisions/ci.md does not exist",
    );
  });

  it('missing status is an error', () => {
    write('build.md', '# Build\n\n## A decision without status\n\nJust text.\n');
    const [, errors] = render(root, domains);
    expect(errors).toHaveLength(1);
    expect(errors[0]).toContain("decision 'A decision without status' needs 'Status:");
  });

  it('main check exit codes', () => {
    const quiet = { root, domains, write: () => {} };
    expect(main([], quiet)).toBe(0);
    expect(main(['--check'], quiet)).toBe(0);
    write('README.md', 'edited by hand\n');
    expect(main(['--check'], quiet)).toBe(1);
  });
});
