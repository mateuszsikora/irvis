/**
 * Generate docs/decisions/README.md, the index of recorded decisions.
 *
 * Usage:
 *     node tools/docs-check/src/decisions-index.ts           write docs/decisions/README.md
 *     node tools/docs-check/src/decisions-index.ts --check   exit 1 if the index is stale
 *     npm run decisions-index [-- --check]
 *
 * Each file docs/decisions/<stem>.md listed in DOMAINS holds one `##` heading
 * per decision, followed by a `Status:` line. The index has one table per
 * domain, in DOMAINS order: decision (linked by heading anchor), file, status.
 *
 * Exit codes:
 *     0  index written, or (with --check) the index is up to date
 *     1  a decision file is malformed; with --check also: the index is stale,
 *        a decision file is not listed in DOMAINS, or a listed domain has no file
 *     2  unknown command-line option
 *
 * Node built-ins only. check-docs.ts imports check() from this file.
 * How it works: docs/features/docs-contract-technical.md#data-flow
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { type Output, parseArgs, processOutput } from './cli.ts';
import { headings } from './markdown.ts';
import { DIGIT, SPACE, readText, repr, sorted, splitLines, strip } from './text.ts';

/** [file stem in docs/decisions/, section title in the index], in index order. */
export type Domains = readonly (readonly [stem: string, title: string])[];

// A list, not an object: Object.entries puts keys that look like integers
// (a stem such as "2027") before the others, whatever the order written here.
export const DOMAINS: Domains = [
  ['docs', 'Documentation contract'],
  ['architecture', 'Architecture'],
];

export const DECISIONS_DIR = 'docs/decisions';
export const INDEX_NAME = 'README.md';
export const GENERATOR = 'tools/docs-check/src/decisions-index.ts';
export const COMMAND = 'npm run decisions-index';

const STATUS_RE = new RegExp(
  String.raw`^Status: (decided|postponed|superseded)(?: \((#${DIGIT}+(?:, #${DIGIT}+)*)\))?[${SPACE}]*$`,
  'u',
);

export interface Decision {
  heading: string;
  slug: string;
  status: string;
  refs: string | undefined;
}

/** Every `##` heading in a decision file, with the Status line under it. */
export function parseDecisions(text: string, name: string): [Decision[], string[]] {
  const lines = splitLines(text);
  const decisions: Decision[] = [];
  const errors: string[] = [];
  for (const h of headings(text)) {
    if (h.level !== 2) continue;
    let statusLine: string | null = null;
    for (let k = h.endLine; k < lines.length; k++) {
      if (strip(lines[k]!)) {
        statusLine = lines[k]!;
        break;
      }
    }
    const m = STATUS_RE.exec(statusLine ?? '');
    if (!m) {
      errors.push(
        `${name}:${h.line}: decision '${h.text}' needs 'Status: decided|postponed|superseded (#N)' ` +
          `as the first line under the heading, found: ${statusLine === null ? 'None' : repr(statusLine)}`,
      );
      continue;
    }
    decisions.push({ heading: h.text, slug: h.slug, status: m[1]!, refs: m[2] });
  }
  return [decisions, errors];
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|');
}

function linkText(text: string): string {
  return cell(text).replaceAll('[', '\\[').replaceAll(']', '\\]');
}

function isFile(path: string): boolean {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}

/** The index text, and the errors found in the decision files. */
export function render(root: string, domains: Domains = DOMAINS): [string, string[]] {
  const out = [
    '# Decisions index',
    '',
    `Generated by \`${GENERATOR}\`, do not edit by hand. Run \`${COMMAND}\` after changing ` +
      'a file in this directory.',
    '',
    'Read this index before deciding anything: it tells you cheaply whether the question was ' +
      'already settled. How to record a decision: ' +
      '[documentation guide](../guides/documentation.md#decisions).',
  ];
  const errors: string[] = [];
  for (const [stem, title] of domains) {
    const path = join(root, DECISIONS_DIR, `${stem}.md`);
    if (!isFile(path)) continue;
    const text = readText(path);
    if (text === null) {
      // Rendering it as empty would drop its decisions from the index without a word.
      errors.push(`${DECISIONS_DIR}/${stem}.md is not valid UTF-8`);
      continue;
    }
    const [decisions, errs] = parseDecisions(text, `${DECISIONS_DIR}/${stem}.md`);
    errors.push(...errs);
    out.push('', `## ${title}`, '');
    if (!decisions.length) {
      out.push('No decisions yet.');
      continue;
    }
    out.push('| Decision | File | Status |', '| --- | --- | --- |');
    for (const d of decisions) {
      const status = d.status + (d.refs ? ` (${d.refs})` : '');
      out.push(
        `| [${linkText(d.heading)}](${stem}.md#${d.slug}) | [${stem}.md](${stem}.md) | ${status} |`,
      );
    }
  }
  return [out.join('\n') + '\n', errors];
}

/** Problems that make the index wrong; empty when it is up to date. */
export function check(root: string, domains: Domains = DOMAINS): string[] {
  const problems: string[] = [];
  const ddir = join(root, DECISIONS_DIR);
  let present = new Set<string>();
  try {
    present = new Set(
      readdirSync(ddir)
        .filter((f) => f.endsWith('.md') && f !== INDEX_NAME)
        .map((f) => f.slice(0, -3)),
    );
  } catch {
    // no directory: every listed domain is missing
  }
  const listed = new Set(domains.map(([stem]) => stem));
  for (const stem of sorted([...present].filter((s) => !listed.has(s)))) {
    problems.push(`${DECISIONS_DIR}/${stem}.md is not listed in DOMAINS in ${GENERATOR}`);
  }
  for (const [stem] of domains) {
    if (!present.has(stem)) {
      problems.push(
        `DOMAINS in ${GENERATOR} lists '${stem}', but ${DECISIONS_DIR}/${stem}.md does not exist`,
      );
    }
  }
  const [text, errors] = render(root, domains);
  problems.push(...errors);
  const index = join(ddir, INDEX_NAME);
  const current = isFile(index) ? readText(index) : null;
  if (current !== text) {
    problems.push(`${DECISIONS_DIR}/${INDEX_NAME} is stale: run \`${COMMAND}\``);
  }
  return problems;
}

export interface MainOptions {
  /** Repository root; by default the one this file is in. */
  root?: string;
  domains?: Domains;
  write?: (text: string) => void;
}

export function main(
  argv: readonly string[] = process.argv.slice(2),
  options: MainOptions = {},
): number {
  const output: Output = options.write
    ? { write: options.write, writeError: options.write }
    : processOutput;
  const parsed = parseArgs(
    argv,
    'decisions-index.ts',
    'Generate or check docs/decisions/README.md.',
    [{ long: '--check', help: 'exit 1 if the index is stale' }],
    output,
  );
  if ('exit' in parsed) return parsed.exit;
  const root = options.root ?? resolve(import.meta.dirname, '../../..');
  const domains = options.domains ?? DOMAINS;
  const print = (line: string) => output.write(`${line}\n`);
  if (parsed.values.has('--check')) {
    const problems = check(root, domains);
    for (const p of problems) print(`decisions-index: ${p}`);
    if (!problems.length) print(`decisions-index: ${DECISIONS_DIR}/${INDEX_NAME} is up to date`);
    return problems.length ? 1 : 0;
  }
  const [text, errors] = render(root, domains);
  if (errors.length) {
    for (const e of errors) print(`decisions-index: ${e}`);
    return 1;
  }
  writeFileSync(join(root, DECISIONS_DIR, INDEX_NAME), text);
  const count = splitLines(text).filter((line) => line.startsWith('| [')).length;
  print(`decisions-index: wrote ${DECISIONS_DIR}/${INDEX_NAME} (${count} decisions)`);
  return 0;
}

if (import.meta.main) process.exitCode = main();
